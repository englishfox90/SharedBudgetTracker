/**
 * Small inline icon set (stroke icons in the Lucide style, ISC-licensed
 * shapes) so the UI does not depend on emoji rendering, which varies by
 * platform. Each icon inherits `currentColor`.
 */
export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  size?: number | string;
  strokeWidth?: number;
  style?: CSSProperties;
}

function Icon({ size = 18, strokeWidth = 2, children, style, ...rest }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={{ flexShrink: 0, verticalAlign: '-0.15em', ...style }}
      {...rest}
    >
      {children}
    </svg>
  );
}

